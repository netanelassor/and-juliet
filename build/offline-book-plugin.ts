import {createHash} from 'node:crypto';
import {readdir, readFile, writeFile} from 'node:fs/promises';
import {extname, resolve} from 'node:path';
import type {Plugin, ResolvedConfig} from 'vite';

/** Build-time inventory, not a runtime crawler. Only local static book files qualify. */
export function offlineBook(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'juliet-explicit-offline-book',
    apply: 'build',
    enforce: 'post',
    configResolved(value) {config = value;},
    async writeBundle() {
      const out = resolve(config.root, config.build.outDir);
      const allowed = new Set(['.html','.js','.mjs','.css','.json','.webmanifest','.webp','.png','.jpg','.jpeg','.svg','.ttf','.otf','.woff','.woff2']);
      async function paths(directory: string, prefix = ''): Promise<string[]> {
        const result: string[] = [];
        for (const item of await readdir(directory, {withFileTypes: true})) {
          const path = prefix + item.name;
          if (item.isDirectory()) result.push(...await paths(resolve(directory, item.name), `${path}/`));
          else if (item.isFile() && allowed.has(extname(path)) && !path.startsWith('offline-book-')) result.push(path);
        }
        return result;
      }
      const names = (await paths(out)).sort((a,b) => Number(b === 'index.html') - Number(a === 'index.html') || a.localeCompare(b));
      for (let i = 1; i <= 48; i++) {
        const scene = String(i).padStart(2, '0');
        for (const kind of ['story','thumbs']) if (!names.includes(`assets/${kind}/scene-${scene}.webp`)) throw new Error(`Offline book inventory is missing ${kind}/scene-${scene}.webp`);
      }
      if (!names.includes('index.html')) throw new Error('Offline book inventory requires index.html');
      const template = await readFile(resolve(config.root, 'build/offline-book-worker.js'), 'utf8');
      const hash = createHash('sha256').update(template);
      const files: {path: string; bytes: number}[] = [];
      for (const path of names) {
        const data = await readFile(resolve(out, path));
        hash.update(path).update(data);
        files.push({path, bytes: data.byteLength});
      }
      const inventory = {
        schema: 1,
        version: hash.digest('hex').slice(0, 16),
        files,
        totalBytes: files.reduce((n, file) => n + file.bytes, 0),
        scenes: 48,
        cleanPlates: names.filter(path => /^assets\/premium\/scene-\d+-clean\.webp$/.test(path)).length,
      };
      await writeFile(resolve(out, 'offline-book-manifest.json'), JSON.stringify(inventory));
      await writeFile(resolve(out, 'offline-book-sw.js'), `/* Generated by the book build. No remote media or credentials. */\nconst BOOK = ${JSON.stringify(inventory)};\n${template}`);
      config.logger.info(`Offline book inventory: ${files.length} files, ${(inventory.totalBytes / 1048576).toFixed(1)} MB, ${inventory.cleanPlates} clean plates. Download requires an explicit reader action.`);
    },
  };
}
